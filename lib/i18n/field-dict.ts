/** 화면 문구 번역 — 없으면 null */
export function trOf(ko: string, lang: FieldLang, vars?: Record<string, string | number>): string | null {
  if (lang === "ko") return null;
  const t = FIELD_DICT[ko];
  return t ? fill(t[lang], vars) : null;
}

/** 안내문(여러 줄 가능) 번역 — 줄마다 사전·패턴으로 찾고, 못 찾은 줄은 비운다. 하나도 없으면 null */
export function trMessage(text: string, lang: FieldLang): string | null {
  if (lang === "ko" || !text) return null;
  let found = false;
  const out = text.split("\n").map(line => {
    const s = line.trim();
    if (!s) return "";
    const d = FIELD_DICT[s];
    if (d) { found = true; return d[lang]; }
    for (const p of FIELD_PATTERNS) {
      const m = s.match(p.re);
      if (m) { found = true; return p.tr[lang].replace(/\{(\d)\}/g, (_, i) => m[Number(i)] ?? ""); }
    }
    return "";
  });
  return found ? out.filter((x, i, a) => x || (i > 0 && a[i - 1])).join("\n").trim() : null;
}
